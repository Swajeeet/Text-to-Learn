const PDFDocument = require("pdfkit");

/**
 * Generate a PDF buffer for a course with its modules.
 * Returns a Buffer that can be sent as a file download.
 *
 * @param {Object} course   - Mongoose Course document
 * @param {Array}  modules  - Array of Module documents for this course
 * @param {Array}  lessons  - Map of moduleId -> lesson array (optional)
 * @returns {Promise<Buffer>}
 */
const generateCoursePDF = (course, modules = [], lessonsMap = {}) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50 });
    const buffers = [];

    doc.on("data", (chunk) => buffers.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(buffers)));
    doc.on("error", reject);

    // ── Cover Page ────────────────────────────────────────────────
    doc
      .fontSize(28)
      .font("Helvetica-Bold")
      .text(course.title, { align: "center" });

    doc.moveDown(0.5);

    doc
      .fontSize(12)
      .font("Helvetica")
      .fillColor("#555555")
      .text(`Difficulty: ${course.difficulty}`, { align: "center" });

    doc.text(
      `Estimated Duration: ${course.estimatedDuration} hours`,
      { align: "center" }
    );

    doc.text(`Language: ${course.language}`, { align: "center" });

    doc.moveDown(1);

    doc
      .fontSize(13)
      .fillColor("#222222")
      .font("Helvetica")
      .text(course.description, { align: "left" });

    doc.moveDown(1.5);

    // ── Horizontal Rule ───────────────────────────────────────────
    doc
      .moveTo(50, doc.y)
      .lineTo(doc.page.width - 50, doc.y)
      .strokeColor("#cccccc")
      .stroke();

    doc.moveDown(1);

    // ── Modules & Lessons ─────────────────────────────────────────
    modules.forEach((module, moduleIndex) => {
      doc
        .fontSize(16)
        .font("Helvetica-Bold")
        .fillColor("#1a1a2e")
        .text(
          `Module ${moduleIndex + 1}: ${module.title}`,
          { continued: false }
        );

      doc.moveDown(0.3);

      if (module.description) {
        doc
          .fontSize(11)
          .font("Helvetica")
          .fillColor("#444444")
          .text(module.description);

        doc.moveDown(0.5);
      }

      // Lessons for this module
      const moduleLessons = lessonsMap[module._id.toString()] || [];

      if (moduleLessons.length > 0) {
        moduleLessons.forEach((lesson, lessonIndex) => {
          doc
            .fontSize(12)
            .font("Helvetica-Bold")
            .fillColor("#333333")
            .text(
              `  Lesson ${lessonIndex + 1}: ${lesson.title}`
            );

          if (lesson.content) {
            doc
              .fontSize(10)
              .font("Helvetica")
              .fillColor("#555555")
              .text(`  ${lesson.content}`, { indent: 20 });
          }

          doc.moveDown(0.3);
        });
      }

      doc.moveDown(0.8);

      // Page break if needed
      if (doc.y > doc.page.height - 100 && moduleIndex < modules.length - 1) {
        doc.addPage();
      }
    });

    // ── Footer ────────────────────────────────────────────────────
    doc.moveDown(2);
    doc
      .fontSize(9)
      .fillColor("#999999")
      .font("Helvetica")
      .text(
        `Generated by Text-to-Learn • ${new Date().toLocaleDateString()}`,
        { align: "center" }
      );

    doc.end();
  });
};

module.exports = { generateCoursePDF };
